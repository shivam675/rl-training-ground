class Autosave:
    """Periodic save into the output document while it is still being written.

    The gap between saves is drawn fresh from [min, max] each time, so saves do
    not fall into a fixed rhythm. Failures are reported and skipped rather than
    raised: the usual cause is the output file being open in Word, and losing a
    whole typing run to that would be worse than missing one save.
    """

    def __init__(self, doc, path, enabled=True,
                 min_seconds=AUTOSAVE_MIN_SECONDS, max_seconds=AUTOSAVE_MAX_SECONDS):
        self.doc = doc
        self.path = Path(path)
        self.enabled = enabled and max_seconds > 0
        self.low = max(0.0, min(min_seconds, max_seconds))
        self.high = max(min_seconds, max_seconds)
        self.saved_once = False
        self.saves = 0
        self.failures = 0
        self.next_at = time.time() + self._gap()

    def _gap(self):
        return random.uniform(self.low, self.high) if self.high > self.low else self.high

    def maybe(self):
        """Save if enough time has passed. Called between blocks."""
        if not self.enabled or time.time() < self.next_at:
            return
        self.save(reason="autosave")

    def save(self, reason="save"):
        """Write the document. Returns True on success; never raises."""
        try:
            if self.saved_once:
                self.doc.Save()
            else:
                self.path.parent.mkdir(parents=True, exist_ok=True)
                self.doc.SaveAs2(str(self.path), FileFormat=WD_FORMAT_XML_DOCUMENT)
                self.saved_once = True
            self.saves += 1
            print("         [%s %d -> %s]" % (reason, self.saves, self.path.name), flush=True)
            return True
        except Exception as exc:
            self.failures += 1
            print("         [%s failed: %s]" % (reason, _short_com_error(exc)), flush=True)
            return False
        finally:
            self.next_at = time.time() + self._gap()


def _short_com_error(exc):
    """Word's COM errors arrive as a nested tuple; pull out the readable sentence."""
    args = getattr(exc, "args", ())
    if len(args) >= 3 and isinstance(args[2], tuple) and len(args[2]) >= 3:
        message = args[2][2]
        if message:
            return str(message).strip().splitlines()[0]
    return str(exc).strip().splitlines()[0]


