@dataclass
class Block:
    kind: str
    text: str = ""
    caption: str = ""
    image: str = ""
    width: float = 0.0
    height: float = 0.0
    rows: list = field(default_factory=list)

    def __repr__(self):  # keeps --dry-run output readable
        head = (self.caption or self.text or self.image)[:64]
        shape = f" {len(self.rows)}x{len(self.rows[0])}" if self.rows else ""
        return f"{self.kind:9}{shape} {head!r}"


FIGURE_RE = re.compile(
    r"^@@figure\s+(?P<file>\S+)(?:\s+(?P<w>[\d.]+)x(?P<h>[\d.]+))?(?:\s*::\s*(?P<cap>.*))?$"
)
DIVIDER_RE = re.compile(r"^:?-{2,}:?$")

AI_DISCLOSURE_REQUIREMENTS = {
    "the dedicated AI-use section": "@@front Use of Generative AI",
    "Anthropic's Claude": "Anthropic's Claude",
    "OpenAI Codex": "OpenAI Codex",
    "Codex's report-only scope": "report writing only",
    "student review of AI output": "All AI-assisted material was reviewed",
}


def validate_ai_disclosure(text):
    """Reject a report source that omits a required GenAI disclosure.

    The report is intentionally explicit about both tools and their different
    scopes. Keeping this check in the generator prevents a later prose edit
    from silently removing the declaration required by the School guidance.
    """
    missing = [
        label for label, phrase in AI_DISCLOSURE_REQUIREMENTS.items()
        if phrase.casefold() not in text.casefold()
    ]
    if missing:
        raise ValueError("incomplete generative-AI disclosure: missing %s" % ", ".join(missing))
    return True


def parse(text):
    """Split report Markdown into (metadata, blocks). Pure text in, pure data out."""
    meta = {}
    lines = text.replace("\r\n", "\n").split("\n")

    if lines and lines[0].strip() == "---":
        for i, line in enumerate(lines[1:], 1):
            if line.strip() == "---":
                lines = lines[i + 1:]
                break
            if ":" in line:
                key, _, val = line.partition(":")
                meta[key.strip()] = val.strip()
        else:
            raise ValueError("front matter opened with --- but never closed")

    blocks = []
    pending_caption = ""
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        i += 1

        if not line:
            continue

        if line.startswith("```"):
            body = []
            while i < len(lines) and lines[i].strip() != "```":
                body.append(lines[i].rstrip())
                i += 1
            if i >= len(lines):
                raise ValueError("code fence opened but never closed")
            i += 1  # step over the closing fence
            blocks.append(Block("code", "\n".join(body)))
            continue

        if line.startswith("@@"):
            word, _, rest = line[2:].partition(" ")
            rest = rest.strip()
            if word == "front":
                blocks.append(Block("front", rest))
            elif word == "toc":
                blocks.append(Block("toc"))
            elif word == "lof":
                blocks.append(Block("lof"))
            elif word == "lot":
                blocks.append(Block("lot"))
            elif word == "bibliography":
                blocks.append(Block("bibliography"))
            elif word == "pagebreak":
                blocks.append(Block("pagebreak"))
            elif word == "sect":
                if rest not in ("front", "body"):
                    raise ValueError("@@sect takes front|body, got %r" % rest)
                blocks.append(Block("sect", rest))
            elif word == "figure":
                m = FIGURE_RE.match(line)
                if not m:
                    raise ValueError("malformed @@figure line: %r" % line)
                blocks.append(
                    Block(
                        "figure",
                        image=m.group("file"),
                        width=float(m.group("w") or FIGURE_DEFAULT_WIDTH_INCHES),
                        height=float(m.group("h") or 0.0),
                        caption=(m.group("cap") or "").strip(),
                    )
                )
            else:
                raise ValueError("unknown directive @@%s" % word)
            continue

        if line.startswith("## "):
            blocks.append(Block("h2", line[3:].strip()))
        elif line.startswith("# "):
            blocks.append(Block("h1", line[2:].strip()))
        elif line.startswith("- "):
            blocks.append(Block("bullet", line[2:].strip()))
        elif line.lower().startswith("table:"):
            pending_caption = line.split(":", 1)[1].strip()
        elif line.startswith("|"):
            rows = []
            i -= 1
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(DIVIDER_RE.match(c) for c in cells):
                    rows.append([c.replace("\\|", "|") for c in cells])
                i += 1
            width = max(len(r) for r in rows)
            rows = [r + [""] * (width - len(r)) for r in rows]
            blocks.append(Block("table", caption=pending_caption, rows=rows))
            pending_caption = ""
        else:
            blocks.append(Block("para", line))

    return meta, blocks


def inline_runs(text):
    """Return ``(text, bold, code)`` runs for the ``**bold**`` and `code` markup.

    Backticks are resolved first, so a ``**`` inside a code span stays literal —
    shell commands and expressions are exactly where stray asterisks turn up. An
    unmatched marker of either kind is preserved literally, so an authoring
    mistake stays visible instead of silently restyling the rest of a paragraph.
    """
    if text.count("`") % 2:
        pieces = [(text, False)]
    else:
        pieces = [
            (piece, bool(index % 2))
            for index, piece in enumerate(text.split("`"))
            if piece
        ]

    runs = []
    for piece, is_code in pieces:
        if is_code or piece.count("**") % 2:
            runs.append((piece, False, is_code))
            continue
        runs.extend(
            (part, bool(index % 2), False)
            for index, part in enumerate(piece.split("**"))
            if part
        )
    return runs


# ----------------------------------------------------------------------- citations

BIBLIOGRAPHY_NS = "http://schemas.openxmlformats.org/officeDocument/2006/bibliography"

# A [n] or [13, 14] marker in the prose. Only digits, so bracketed words such as
# [Online] are left alone.
CITATION_RE = re.compile(r"\[(\d+(?:\s*,\s*\d+)*)\]")


def load_sources(path=SOURCES_JSON):
    """Read report/sources.json into ``{number: entry}`` keyed by src<n> tag.

    The number is what a [n] marker in the prose refers to. It is not the number
    Word prints: Word's IEEE renderer numbers by first appearance in the
    document, and assigns those numbers itself.
    """
    import json

    data = json.loads(Path(path).read_text(encoding="utf-8"))
    sources = {}
    for entry in data["sources"]:
        tag = entry["tag"]
        if not tag.startswith("src") or not tag[3:].isdigit():
            raise ValueError("source tag must look like src<n>, got %r" % tag)
        number = int(tag[3:])
        if number in sources:
            raise ValueError("duplicate source tag %r" % tag)
        sources[number] = entry
    return sources


def source_xml(entry):
    """Turn one sources.json entry into the XML Word's Sources.Add expects.

    Every key other than ``tag``, ``type`` and ``author`` is passed through as a
    bibliography field of the same name, so adding a field to the JSON needs no
    change here. The author is written as a corporate name rather than a parsed
    name list: the entries carry pre-formatted author strings, including the
    'et al.' forms, and Word renders a corporate author verbatim.
    """
    from xml.sax.saxutils import escape

    parts = [
        "<b:Tag>%s</b:Tag>" % escape(entry["tag"]),
        "<b:SourceType>%s</b:SourceType>" % escape(entry["type"]),
    ]
    if entry.get("author"):
        parts.append(
            "<b:Author><b:Author><b:Corporate>%s</b:Corporate></b:Author></b:Author>"
            % escape(entry["author"])
        )
    for key, value in entry.items():
        if key in ("tag", "type", "author") or key.startswith("_"):
            continue
        parts.append("<b:%s>%s</b:%s>" % (key, escape(str(value)), key))
    return '<b:Source xmlns:b="%s">%s</b:Source>' % (BIBLIOGRAPHY_NS, "".join(parts))


def citation_code(numbers, language=CITATION_LANGUAGE):
    """Field code for one [n] marker. Several numbers merge into one citation."""
    first, rest = numbers[0], numbers[1:]
    merged = "".join(" \\m src%d" % n for n in rest)
    return "CITATION src%d%s \\l %d" % (first, merged, language)


