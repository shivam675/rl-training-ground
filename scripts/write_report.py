"""Launch Microsoft Word and write the EasyRTG report into it, live.

The report TEXT is not in this file. It lives in:

    report/report.md          <-- edit this to change what the report says
    report/media/*.png        <-- figures, regenerated by scripts/make_report_figures.py

This script only turns that Markdown into a Word document. Because it drives a real
Word instance over COM, the result carries Word-native artifacts a generated .docx
cannot: an updatable TOC, SEQ-numbered figure and table captions feeding a real List
of Figures and List of Tables, live CITATION fields and a BIBLIOGRAPHY field in IEEE
style, and PAGE-field footers.

Everything adjustable is in the SETTINGS block below — typing speed, autosave timing,
paths, fonts, sizes, margins, spacing. Edit those values rather than hunting through
the code. Command-line flags override them for one run without editing anything:

    .venv/Scripts/python.exe scripts/write_report.py                # watch it type
    .venv/Scripts/python.exe scripts/write_report.py --cps 40       # slow demo pace
    .venv/Scripts/python.exe scripts/write_report.py --fast         # no pacing
    .venv/Scripts/python.exe scripts/write_report.py --no-pauses    # no thinking pauses
    .venv/Scripts/python.exe scripts/write_report.py --headless --pdf
    .venv/Scripts/python.exe scripts/write_report.py --dry-run      # plan only, no Word

Markdown dialect used by report.md (everything else is ordinary Markdown):
    ---  key: value  ---     title-page / header metadata
    # / ##                   Heading 1 / Heading 2
    @@front <text>           front-matter heading (Declaration, Abstract, ...)
    @@toc @@lof @@lot        Word TOC / table-of-figures / table-of-tables fields
    @@bibliography           Word BIBLIOGRAPHY field, filled from report/sources.json
    @@sect front|body        section break; the first one starts the page count at 1
    @@pagebreak              page break
    @@figure <file> <W>x<H> :: <caption>
    Table: <caption>         caption for the pipe table that follows
    | a | b |                pipe table (first row is the header row)
    - item                   bullet
    ```                      fenced code block, kept verbatim and never justified
    `code`                   inline monospace span
    **bold**                 inline bold span
    [3] or [13, 14]          becomes a Word CITATION field for that source
"""

