class WordWriter:
    """Types a parsed report into a live Word document."""

    def __init__(self, app, doc, cps=CHARS_PER_SECOND, jitter=TYPING_JITTER,
                 chunk=TYPING_CHUNK_CHARS, pauses=THINKING_PAUSES,
                 pause_chars=(PAUSE_AFTER_CHARS_MIN, PAUSE_AFTER_CHARS_MAX),
                 pause_seconds=(PAUSE_SECONDS_MIN, PAUSE_SECONDS_MAX),
                 pause_at_boundary=PAUSE_AT_WORD_BOUNDARY, sources=None):
        self.app = app
        self.doc = doc
        self.sources = load_sources() if sources is None else sources
        self.sel = app.Selection
        self.cps = cps
        self.jitter = max(0.0, min(1.0, jitter))
        self.chunk = max(1, int(chunk))
        self.n_fig = 0
        self.n_tbl = 0

        # Thinking pauses: wait a random X seconds after a random Y characters.
        low, high = min(pause_chars), max(pause_chars)
        self.pause_chars = (max(1, int(low)), max(1, int(high)))
        self.pause_seconds = (min(pause_seconds), max(pause_seconds))
        self.pause_at_boundary = pause_at_boundary
        self.pauses_enabled = bool(pauses) and high > 0
        self.n_pauses = 0
        self.paused_seconds = 0.0
        self.chars_until_pause = self.next_pause_gap()

    # -- thinking pauses ---------------------------------------------------

    def next_pause_gap(self):
        """How many characters until the next pause. Fresh random draw each time."""
        if not self.pauses_enabled:
            return float("inf")
        low, high = self.pause_chars
        return random.randint(low, high) if high > low else low

    def may_pause_after(self, piece, consumed, total):
        """Whether a pause is allowed to land here.

        With PAUSE_AT_WORD_BOUNDARY on, a pause waits for whitespace, punctuation
        or the end of the text, so it never breaks a word mid-way — which reads as
        a stutter rather than as someone thinking.
        """
        if not self.pause_at_boundary or consumed >= total:
            return True
        return bool(piece) and piece[-1] in PAUSE_BOUNDARY_CHARS

    def think(self):
        """Stop typing for a random X seconds, then arm the next pause."""
        low, high = self.pause_seconds
        seconds = random.uniform(low, high) if high > low else low
        if seconds > 0:
            time.sleep(seconds)
        self.n_pauses += 1
        self.paused_seconds += seconds
        self.chars_until_pause = self.next_pause_gap()

    # -- primitives --------------------------------------------------------

    def at_end(self):
        self.sel.EndKey(WD_STORY)

    def set_style(self, name):
        self.sel.Style = self.doc.Styles(name)

    def type_text(self, text):
        """Type text at the caret, one keystroke at a time so it can be watched.

        At TYPING_CHUNK_CHARS = 1 every character — letters, spaces, capitals,
        punctuation — is a separate TypeText call, so the caret advances exactly as
        it would under a human typing. Word's COM round-trip is about 0.8ms, which
        is the real ceiling on speed; the sleep below only slows things further.
        """
        if self.cps <= 0:
            self.sel.TypeText(text)
            return
        chunk = self.chunk
        delay = chunk / self.cps
        total = len(text)
        for start in range(0, total, chunk):
            piece = text[start:start + chunk]
            self.sel.TypeText(piece)
            if delay > 0.001:
                if self.jitter:
                    time.sleep(delay * random.uniform(1 - self.jitter, 1 + self.jitter))
                else:
                    time.sleep(delay)
            # The character budget runs continuously across the whole document, so
            # pauses fall wherever they fall rather than once per paragraph.
            self.chars_until_pause -= len(piece)
            if self.chars_until_pause <= 0 and self.may_pause_after(piece, start + chunk, total):
                self.think()

    def type_inline_text(self, text):
        """Type the small inline-markup subset used by report prose.

        [n] markers are lifted out first and inserted as Word CITATION fields, so
        the numbers in the finished document are Word's, not the ones typed here.
        Whatever falls between them is typed as bold, code and plain runs.
        """
        cursor = 0
        for match in CITATION_RE.finditer(text):
            self.type_marked_up(text[cursor:match.start()])
            numbers = [int(n) for n in match.group(1).split(",")]
            unknown = [n for n in numbers if n not in self.sources]
            if unknown:
                raise ValueError(
                    "citation %s has no entry in %s"
                    % (match.group(0), Path(SOURCES_JSON).name)
                )
            self.citation(numbers)
            cursor = match.end()
        self.type_marked_up(text[cursor:])

    def type_marked_up(self, text):
        """Type one stretch of prose, honouring **bold** and `code` runs."""
        if not text:
            return
        font = self.sel.Font
        previous = (font.Bold, font.Name, font.Size)
        try:
            for piece, bold, code in inline_runs(text):
                font.Bold = bold
                font.Name = CODE_FONT if code else BODY_FONT
                font.Size = CODE_INLINE_SIZE if code else BODY_SIZE
                self.type_text(piece)
        finally:
            font.Bold, font.Name, font.Size = previous

    def add_field(self, code):
        self.sel.Fields.Add(self.sel.Range, WD_FIELD_EMPTY, code, False)
        self.sel.Collapse(WD_COLLAPSE_END)

    def citation(self, numbers):
        """Insert a CITATION field for one [n] marker.

        Word wraps a citation in a content control, and a selection left inside
        one rejects the next TypeText with 'The Insert statement is currently
        disabled'. Jumping to the end of the story steps back outside it — which
        is also exactly where the next character belongs, since prose is always
        typed at the end of the document.
        """
        self.sel.Fields.Add(self.sel.Range, WD_FIELD_EMPTY, citation_code(numbers), False)
        self.at_end()

    def paragraph(self, style, text, alignment=None, inline=False):
        self.at_end()
        self.set_style(style)
        if alignment is not None:
            self.sel.ParagraphFormat.Alignment = alignment
        if text:
            if inline:
                self.type_inline_text(text)
            else:
                self.type_text(text)
        self.sel.TypeParagraph()

    # -- document scaffolding ---------------------------------------------

    def ensure_styles(self):
        """Apply the typography from the SETTINGS block to Word's styles."""
        doc = self.doc
        normal = doc.Styles("Normal")
        normal.Font.Name = BODY_FONT
        normal.Font.Size = BODY_SIZE
        normal.ParagraphFormat.Alignment = BODY_ALIGNMENT
        normal.ParagraphFormat.LineSpacingRule = WD_LINE_SPACE_MULTIPLE
        normal.ParagraphFormat.LineSpacing = BODY_LINE_SPACING
        normal.ParagraphFormat.SpaceAfter = BODY_SPACE_AFTER

        headings = (
            ("Heading 1", HEADING1_FONT, HEADING1_SIZE,
             HEADING1_SPACE_BEFORE, HEADING1_SPACE_AFTER),
            ("Heading 2", HEADING2_FONT, HEADING2_SIZE,
             HEADING2_SPACE_BEFORE, HEADING2_SPACE_AFTER),
        )
        for name, font, size, before, after in headings:
            st = doc.Styles(name)
            st.Font.Name = font
            st.Font.Size = size
            st.Font.Bold = True
            st.Font.Color = HEADING_COLOUR
            st.ParagraphFormat.Alignment = WD_ALIGN_LEFT
            st.ParagraphFormat.LineSpacingRule = WD_LINE_SPACE_SINGLE
            st.ParagraphFormat.SpaceBefore = before
            st.ParagraphFormat.SpaceAfter = after
            st.ParagraphFormat.KeepWithNext = True

        cap = doc.Styles("Caption")
        cap.Font.Name = BODY_FONT
        cap.Font.Size = CAPTION_SIZE
        cap.Font.Bold = CAPTION_BOLD
        cap.Font.Italic = CAPTION_ITALIC
        cap.Font.Color = CAPTION_COLOUR
        cap.ParagraphFormat.Alignment = WD_ALIGN_CENTER
        cap.ParagraphFormat.LineSpacingRule = WD_LINE_SPACE_SINGLE
        cap.ParagraphFormat.SpaceBefore = CAPTION_SPACE_BEFORE
        cap.ParagraphFormat.SpaceAfter = CAPTION_SPACE_AFTER
        cap.ParagraphFormat.KeepWithNext = True

        fm = self._style(FRONT_MATTER_STYLE, normal)
        fm.Font.Name = BODY_FONT
        fm.Font.Size = FRONT_MATTER_SIZE
        fm.Font.Bold = True
        fm.ParagraphFormat.Alignment = WD_ALIGN_CENTER
        fm.ParagraphFormat.LineSpacingRule = WD_LINE_SPACE_SINGLE
        fm.ParagraphFormat.SpaceAfter = FRONT_MATTER_SPACE_AFTER

        code = self._style(CODE_BLOCK_STYLE, normal)
        code.Font.Name = CODE_FONT
        code.Font.Size = CODE_BLOCK_SIZE
        # Left, never justified: justifying a shell command stretches the spaces
        # between its arguments into gaps and makes it unreadable.
        code.ParagraphFormat.Alignment = WD_ALIGN_LEFT
        code.ParagraphFormat.LineSpacingRule = WD_LINE_SPACE_SINGLE
        code.ParagraphFormat.LeftIndent = CODE_BLOCK_INDENT
        code.ParagraphFormat.SpaceBefore = CODE_BLOCK_SPACE_BEFORE
        code.ParagraphFormat.SpaceAfter = CODE_BLOCK_SPACE_AFTER

        # Word owns the paragraphs a BIBLIOGRAPHY field produces and applies its
        # own built-in style to them, so the single spacing goes on that style
        # rather than on one of ours. Missing on an unusual Word build is not
        # worth failing a run over.
        try:
            bib = self.doc.Styles(BIBLIOGRAPHY_STYLE)
        except Exception:
            return
        bib.Font.Name = BODY_FONT
        bib.Font.Size = BIBLIOGRAPHY_SIZE
        bib.ParagraphFormat.Alignment = WD_ALIGN_LEFT
        bib.ParagraphFormat.LineSpacingRule = WD_LINE_SPACE_SINGLE  # required: single
        bib.ParagraphFormat.SpaceAfter = BIBLIOGRAPHY_SPACE_AFTER
        bib.ParagraphFormat.LeftIndent = BIBLIOGRAPHY_HANGING_INDENT
        bib.ParagraphFormat.FirstLineIndent = -BIBLIOGRAPHY_HANGING_INDENT

    def register_sources(self, style=CITATION_STYLE):
        """Load report/sources.json into the document's own source list.

        Word renders and numbers citations from these, so the CITATION fields the
        prose inserts have something to resolve against. Sources.Add rejects a
        tag that already exists, which only happens when a run is repeated into
        an existing document, so an existing tag is left alone.
        """
        bibliography = self.doc.Bibliography
        try:
            bibliography.BibliographyStyle = style
        except Exception as exc:
            print("         [citation style %r unavailable: %s]"
                  % (style, _short_com_error(exc)), flush=True)
        for _, entry in sorted(self.sources.items()):
            try:
                bibliography.Sources.Add(source_xml(entry))
            except Exception as exc:
                raise RuntimeError(
                    "Word rejected source %s: %s" % (entry["tag"], _short_com_error(exc))
                )

    def _style(self, name, base):
        """Fetch a custom paragraph style, creating it on first use."""
        try:
            style = self.doc.Styles(name)
        except Exception:
            style = self.doc.Styles.Add(name, WD_STYLE_TYPE_PARAGRAPH)
        style.BaseStyle = base
        return style

    def page_setup(self):
        for sec in self.doc.Sections:
            ps = sec.PageSetup
            ps.TopMargin = PAGE_MARGIN_POINTS
            ps.BottomMargin = PAGE_MARGIN_POINTS
            ps.LeftMargin = PAGE_MARGIN_POINTS
            ps.RightMargin = PAGE_MARGIN_POINTS
            ps.DifferentFirstPageHeaderFooter = True

    def title_page(self, meta):
        cfg = TITLE_PAGE

        def centred(text, size, bold=False, space_after=12, space_before=0):
            self.at_end()
            self.set_style("Normal")
            pf = self.sel.ParagraphFormat
            pf.Alignment = WD_ALIGN_CENTER
            pf.SpaceAfter = space_after
            pf.SpaceBefore = space_before
            pf.LineSpacingRule = WD_LINE_SPACE_SINGLE
            self.sel.Font.Size = size
            self.sel.Font.Bold = bold
            if text:
                self.type_text(text)
            self.sel.TypeParagraph()
            self.sel.Font.Bold = False
            self.sel.Font.Size = BODY_SIZE

        detail = cfg["detail_size"]
        centred("", BODY_SIZE, space_after=cfg["top_gap"])
        centred(meta.get("kicker", "FINAL PROJECT REPORT"), cfg["kicker_size"],
                bold=True, space_after=cfg["kicker_gap"])
        centred(meta.get("title", "Report"), cfg["title_size"],
                bold=True, space_after=cfg["title_gap"])
        if meta.get("subtitle"):
            centred(meta["subtitle"], cfg["subtitle_size"], space_after=cfg["subtitle_gap"])
        centred(meta.get("author", ""), cfg["author_size"], bold=True, space_after=0)
        if meta.get("student_id"):
            centred("Student ID: " + meta["student_id"], detail, space_after=0)
        if meta.get("supervisor"):
            centred("Supervisor: " + meta["supervisor"], detail,
                    space_after=0, space_before=cfg["supervisor_gap"])
        if meta.get("inspector"):
            centred("Inspector: " + meta["inspector"], detail, space_after=0)
        if meta.get("programme"):
            centred(meta["programme"], detail, bold=True,
                    space_after=0, space_before=cfg["programme_gap"])
        parts = [p.strip() for p in meta.get("affiliation", "").split("|") if p.strip()]
        for n, part in enumerate(parts):
            before = 0 if (n or meta.get("programme")) else cfg["affiliation_gap"]
            centred(part, detail, space_after=0, space_before=before)
        if meta.get("word_count"):
            centred("Word count: " + meta["word_count"], detail,
                    space_after=0, space_before=cfg["word_count_gap"])

    def new_section(self, restart_numbering):
        """Start a new section whose footer is a centred page number and nothing else.

        There is no running header, and no roman numbering: the count starts at 1
        on the first section after the title page and runs unbroken to the end.
        Word suppresses a footer on a section's first page when
        DifferentFirstPageHeaderFooter is set, which is wanted on the title page
        and nowhere else, so it is cleared here.
        """
        self.at_end()
        self.sel.InsertBreak(WD_SECTION_BREAK_NEXT_PAGE)
        self.at_end()
        self.set_style("Normal")
        self.sel.ParagraphFormat.Alignment = BODY_ALIGNMENT
        self.sel.ParagraphFormat.SpaceBefore = 0
        self.sel.Font.Bold = False
        self.sel.Font.Size = BODY_SIZE

        sec = self.doc.Sections(self.doc.Sections.Count)
        sec.PageSetup.DifferentFirstPageHeaderFooter = False

        header = sec.Headers(WD_HEADER_FOOTER_PRIMARY)
        header.LinkToPrevious = False
        header.Range.Text = ""

        footer = sec.Footers(WD_HEADER_FOOTER_PRIMARY)
        footer.LinkToPrevious = False
        footer.Range.Text = ""
        footer.Range.Fields.Add(footer.Range, WD_FIELD_EMPTY, "PAGE", False)
        footer.Range.Font.Name = BODY_FONT
        footer.Range.Font.Size = FOOTER_FONT_SIZE
        footer.Range.ParagraphFormat.Alignment = WD_ALIGN_CENTER

        numbers = footer.PageNumbers
        numbers.NumberStyle = WD_PAGE_NUMBER_ARABIC
        numbers.RestartNumberingAtSection = restart_numbering
        if restart_numbering:
            numbers.StartingNumber = 1

    # -- blocks -----------------------------------------------------------

    def caption(self, kind, text, keep_with_next=False):
        self.at_end()
        self.set_style("Caption")
        self.sel.ParagraphFormat.Alignment = WD_ALIGN_CENTER
        self.sel.ParagraphFormat.KeepWithNext = keep_with_next
        self.sel.TypeText(kind + " ")
        self.add_field("SEQ %s \\* ARABIC" % kind)
        self.sel.TypeText(". ")
        self.type_text(text)
        self.sel.TypeParagraph()
        self.sel.ParagraphFormat.KeepWithNext = False

    def figure(self, block, media_dir):
        path = Path(media_dir) / block.image
        if not path.exists():
            raise FileNotFoundError("figure not found: %s" % path)
        self.at_end()
        self.set_style("Normal")
        self.sel.ParagraphFormat.Alignment = WD_ALIGN_CENTER
        self.sel.ParagraphFormat.SpaceAfter = FIGURE_SPACE_AFTER
        shape = self.doc.InlineShapes.AddPicture(str(path), False, True, self.sel.Range)
        if block.width:
            ratio = (shape.Height / shape.Width) if shape.Width else 1.0
            shape.Width = block.width * 72
            shape.Height = (block.height * 72) if block.height else (shape.Width * ratio)
        self.at_end()
        self.sel.TypeParagraph()
        self.n_fig += 1
        if block.caption:
            self.caption("Figure", block.caption)

    def table(self, block):
        rows, cols = len(block.rows), len(block.rows[0])
        # Short tables are easier to read as a unit. Keep the caption and rows
        # together when the table can reasonably fit on one page; long appendix
        # tables still paginate normally with a repeated header row.
        keep_together = rows <= 10 and sum(len(value) for row in block.rows for value in row) <= 1800
        if block.caption:
            self.n_tbl += 1
            self.caption("Table", block.caption, keep_with_next=keep_together)
        self.at_end()
        self.set_style("Normal")
        tbl = self.doc.Tables.Add(self.sel.Range, rows, cols)
        try:
            tbl.Style = TABLE_STYLE
        except Exception:
            tbl.Borders.InsideLineStyle = 1
            tbl.Borders.OutsideLineStyle = 1
        # Format before filling, so the cells look right while they are being typed
        # rather than snapping into shape afterwards.
        tbl.Range.Font.Name = BODY_FONT
        tbl.Range.Font.Size = TABLE_FONT_SIZE
        tbl.Range.ParagraphFormat.Alignment = WD_ALIGN_LEFT
        tbl.Range.ParagraphFormat.LineSpacingRule = WD_LINE_SPACE_SINGLE
        tbl.Range.ParagraphFormat.SpaceAfter = TABLE_SPACE_AFTER
        for r, row in enumerate(block.rows, start=1):
            for c, value in enumerate(row, start=1):
                if not value:
                    continue
                if TYPE_TABLE_CELLS and self.cps > 0:
                    # Park the caret at the start of the cell and type into it, so a
                    # table fills in the same way the prose does. Collapsing matters:
                    # a cell's Range covers the end-of-cell mark, and typing over a
                    # live selection would eat it and merge the cells.
                    cell = tbl.Cell(r, c)
                    cell.Range.Select()
                    self.sel.Collapse(WD_COLLAPSE_START)
                    self.type_text(value)
                else:
                    tbl.Cell(r, c).Range.Text = value
        tbl.Rows(1).Range.Font.Bold = TABLE_HEADER_BOLD
        tbl.Rows(1).HeadingFormat = TABLE_REPEAT_HEADER_ROW
        for row_number in range(1, rows + 1):
            tbl.Rows(row_number).AllowBreakAcrossPages = False
            if keep_together and row_number < rows:
                tbl.Rows(row_number).Range.ParagraphFormat.KeepWithNext = True
        tbl.AutoFitBehavior(WD_AUTOFIT_WINDOW)
        self.at_end()
        self.set_style("Normal")
        self.sel.ParagraphFormat.Alignment = BODY_ALIGNMENT
        self.sel.TypeParagraph()

    def code_block(self, text):
        """Write a fenced block verbatim, one paragraph per line.

        Lines are separate paragraphs rather than one paragraph with line breaks
        so a long command can break across a page without dragging the whole
        block with it.
        """
        lines = text.split("\n")
        for n, line in enumerate(lines):
            self.at_end()
            self.set_style(CODE_BLOCK_STYLE)
            self.sel.ParagraphFormat.KeepWithNext = n < len(lines) - 1
            self.type_text(line)
            self.sel.TypeParagraph()
        self.at_end()
        self.set_style("Normal")
        self.sel.ParagraphFormat.Alignment = BODY_ALIGNMENT
        self.sel.ParagraphFormat.KeepWithNext = False

    def field_block(self, code):
        self.at_end()
        self.set_style("Normal")
        self.sel.ParagraphFormat.Alignment = WD_ALIGN_LEFT
        self.add_field(code)
        self.at_end()
        self.sel.TypeParagraph()

    def write(self, meta, blocks, media_dir, on_block=None):
        self.title_page(meta)
        sections = 0
        for n, block in enumerate(blocks, start=1):
            if on_block:
                on_block(n, block)
            kind = block.kind
            if kind == "sect":
                # Only the first section restarts the count; the rest continue it,
                # so page 1 is the page after the title page and nothing repeats.
                sections += 1
                self.new_section(restart_numbering=sections == 1)
            elif kind == "pagebreak":
                self.at_end()
                self.sel.InsertBreak(WD_PAGE_BREAK)
            elif kind == "front":
                self.paragraph(FRONT_MATTER_STYLE, block.text, WD_ALIGN_CENTER)
            elif kind == "h1":
                self.paragraph("Heading 1", block.text, WD_ALIGN_LEFT)
            elif kind == "h2":
                self.paragraph("Heading 2", block.text, WD_ALIGN_LEFT)
            elif kind == "para":
                self.paragraph("Normal", block.text, BODY_ALIGNMENT, inline=True)
            elif kind == "bullet":
                self.paragraph("List Bullet", block.text, WD_ALIGN_LEFT, inline=True)
            elif kind == "code":
                self.code_block(block.text)
            elif kind == "figure":
                self.figure(block, media_dir)
            elif kind == "table":
                self.table(block)
            elif kind == "toc":
                self.field_block(TOC_CODE)
            elif kind == "lof":
                self.field_block(LOF_CODE)
            elif kind == "lot":
                self.field_block(LOT_CODE)
            elif kind == "bibliography":
                self.field_block("BIBLIOGRAPHY \\l %d" % CITATION_LANGUAGE)
            else:
                raise ValueError("cannot render block kind %r" % kind)

    def finish(self):
        """Populate every field twice so page numbers settle after repagination."""
        for _ in range(2):
            self.doc.Fields.Update()
            for toc in self.doc.TablesOfContents:
                toc.Update()
            for tof in self.doc.TablesOfFigures:
                tof.Update()
            self.doc.Repaginate()
            # Doc.Fields covers the main story only; footer PAGE fields keep the
            # stale cached number unless their own story is updated too.
            for sec in self.doc.Sections:
                for story in (sec.Headers, sec.Footers):
                    for which in (1, 2, 3):  # primary, first page, even pages
                        try:
                            story(which).Range.Fields.Update()
                        except Exception:
                            pass


