def quiet_autocorrect(app):
    """Stop Word 'helpfully' rewriting shell commands and URLs as we type them."""
    saved = {}
    for name in AUTOCORRECT_FLAGS:
        try:
            saved[("ac", name)] = getattr(app.AutoCorrect, name)
            setattr(app.AutoCorrect, name, False)
        except Exception:
            pass
    for name in AUTOFORMAT_FLAGS:
        try:
            saved[("op", name)] = getattr(app.Options, name)
            setattr(app.Options, name, False)
        except Exception:
            pass
    return saved


def restore_autocorrect(app, saved):
    for (where, name), value in saved.items():
        try:
            setattr(app.AutoCorrect if where == "ac" else app.Options, name, value)
        except Exception:
            pass


# Measured cost of one TypeText round-trip to Word, used only to estimate runtime.
COM_KEYSTROKE_SECONDS = 0.0008


def typed_characters(blocks):
    """Every character the run will actually type, table cells included."""
    total = 0
    for block in blocks:
        total += len(block.text) + len(block.caption)
        if block.kind == "table" and TYPE_TABLE_CELLS:
            total += sum(len(cell) for row in block.rows for cell in row)
    return total


def dry_run(args, meta, blocks):
    print("%s  ->  %s" % (args.source, args.out))
    for key, value in meta.items():
        print("  meta %s: %s" % (key, value))
    counts = {}
    for n, block in enumerate(blocks, start=1):
        counts[block.kind] = counts.get(block.kind, 0) + 1
        print("  %4d %r" % (n, block))
    chars = typed_characters(blocks)
    print("\n  %d blocks, %d characters to type" % (len(blocks), chars))
    print("  " + ", ".join("%s=%d" % kv for kv in sorted(counts.items())))
    if args.cps > 0 and not args.fast:
        chunk = max(1, int(TYPING_CHUNK_CHARS))
        keystrokes = chars / chunk
        # Each keystroke costs its pause plus a COM round-trip; the round-trip is
        # what caps throughput once CHARS_PER_SECOND goes high.
        seconds = keystrokes * (chunk / args.cps + COM_KEYSTROKE_SECONDS)
        print("  %d chars in bursts of %d at %g chars/s -> ~%.0fs of keystrokes"
              % (chars, chunk, args.cps, seconds))
        print("  (keystrokes only; styling, figures and TOC updates add roughly as"
              " much again. Character-by-character tops out near %.0f chars/s.)"
              % (1.0 / COM_KEYSTROKE_SECONDS))
        if args.pauses and PAUSE_AFTER_CHARS_MAX > 0:
            gap = (PAUSE_AFTER_CHARS_MIN + PAUSE_AFTER_CHARS_MAX) / 2
            length = (PAUSE_SECONDS_MIN + PAUSE_SECONDS_MAX) / 2
            print("  plus ~%.0f thinking pauses of %.1fs on average -> ~%.0fs more"
                  % (chars / gap, length, chars / gap * length))
    if args.autosave:
        print("  autosave every %g-%gs into %s"
              % (AUTOSAVE_MIN_SECONDS, AUTOSAVE_MAX_SECONDS, args.out.name))
    return 0


def run(args):
    # Word resolves relative paths against its own working directory, not ours.
    args.source = args.source.resolve()
    args.media = args.media.resolve()
    args.out = args.out.resolve()
    if not args.source.exists():
        sys.exit("source not found: %s\nrun scripts/extract_report.py first" % args.source)
    source_text = args.source.read_text(encoding="utf-8")
    validate_ai_disclosure(source_text)
    meta, blocks = parse(source_text)
    if args.limit:
        blocks = blocks[:args.limit]

    if args.dry_run:
        return dry_run(args, meta, blocks)

    import pythoncom  # noqa: F401  (initialises COM for this thread)
    import win32com.client as com

    app = com.DispatchEx("Word.Application")
    saved = quiet_autocorrect(app) if QUIET_AUTOCORRECT else {}
    doc = None
    try:
        app.Visible = not args.headless
        if not args.headless:
            try:
                app.WindowState = 1  # wdWindowStateNormal
                app.Activate()
            except Exception:
                pass
        doc = app.Documents.Add()
        writer = WordWriter(app, doc, cps=0 if args.fast else args.cps, pauses=args.pauses)
        writer.ensure_styles()
        writer.page_setup()
        writer.register_sources()

        autosave = Autosave(doc, args.out, enabled=args.autosave)
        total = len(blocks)
        started = time.time()

        def progress(n, block):
            if args.progress:
                print("[%4d/%d] %r" % (n, total, block), flush=True)
            autosave.maybe()

        writer.write(meta, blocks, args.media, on_block=progress)
        print("updating TOC, figure and table lists ...", flush=True)
        writer.finish()

        # Unlike the periodic saves, this one must not be swallowed.
        args.out.parent.mkdir(parents=True, exist_ok=True)
        if autosave.saved_once:
            doc.Save()
        else:
            doc.SaveAs2(str(args.out), FileFormat=WD_FORMAT_XML_DOCUMENT)
        note = ""
        if autosave.saves:
            note = ", %d autosaves" % autosave.saves
        if autosave.failures:
            note += ", %d autosaves failed" % autosave.failures
        if writer.n_pauses:
            note += ", %d thinking pauses totalling %.0fs" % (
                writer.n_pauses, writer.paused_seconds)
        print(
            "saved %s (%d pages) in %.0fs%s"
            % (args.out, doc.ComputeStatistics(WD_STATISTIC_PAGES), time.time() - started, note)
        )
        if args.pdf:
            pdf = args.out.with_suffix(".pdf")
            # CreateBookmarks defaults to none, which leaves the PDF without a
            # navigation pane; the TOC's own links survive export either way.
            doc.ExportAsFixedFormat(
                str(pdf), WD_EXPORT_FORMAT_PDF,
                CreateBookmarks=WD_EXPORT_CREATE_HEADING_BOOKMARKS,
            )
            print("saved %s" % pdf)
        if not args.keep_open:
            doc.Close(WD_DO_NOT_SAVE_CHANGES)
            doc = None
            app.Quit()
        return 0
    except Exception:
        if doc is not None and args.headless:
            doc.Close(WD_DO_NOT_SAVE_CHANGES)
            app.Quit()
        raise
    finally:
        restore_autocorrect(app, saved)


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    # Every default here comes from the SETTINGS block at the top of this file.
    ap.add_argument("--source", type=Path, default=SOURCE_MARKDOWN,
                    help="report Markdown (default: %(default)s)")
    ap.add_argument("--media", type=Path, default=MEDIA_DIR)
    ap.add_argument("--out", type=Path, default=OUTPUT_DOCX)
    ap.add_argument("--cps", type=float, default=CHARS_PER_SECOND,
                    help="typing speed, chars/sec (default %(default)g)")
    ap.add_argument("--fast", action="store_true", default=not TYPEWRITER,
                    help="no pacing at all")
    ap.add_argument("--headless", action="store_true", default=not SHOW_WORD,
                    help="keep the Word window hidden")
    ap.add_argument("--pdf", action="store_true", default=EXPORT_PDF,
                    help="also export a PDF next to the .docx")
    ap.add_argument("--keep-open", action="store_true", default=KEEP_OPEN_WHEN_DONE,
                    help="leave the document open in Word")
    ap.add_argument("--no-autosave", dest="autosave", action="store_false", default=AUTOSAVE,
                    help="only save once, at the end")
    ap.add_argument("--no-pauses", dest="pauses", action="store_false", default=THINKING_PAUSES,
                    help="type straight through, no thinking pauses")
    ap.add_argument("--quiet", dest="progress", action="store_false", default=SHOW_PROGRESS,
                    help="do not print a line per block")
    ap.add_argument("--limit", type=int, default=0, help="render only the first N blocks")
    ap.add_argument("--dry-run", action="store_true", help="print the block plan, never open Word")
    sys.exit(run(ap.parse_args()))


if __name__ == "__main__":
    main()
