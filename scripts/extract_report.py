"""Extract EasyRTG_Project_Report_Shivam_Chavan.docx into report/report.md + report/media/.

One-off-but-rerunnable: turns the only copy of the report (a .docx) into a diffable
Markdown source that scripts/write_report.py renders back into Word.

    .venv/Scripts/python.exe scripts/extract_report.py [--docx PATH] [--out DIR]
"""

from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

import docx
from docx.oxml.ns import qn
from docx.table import Table
from docx.text.paragraph import Paragraph

EMU_PER_INCH = 914400
# Styles whose paragraphs are generated by Word fields; never carried into the source.
GENERATED_STYLES = {"TOC 1", "TOC 2", "TOC 3", "toc 1", "toc 2", "toc 3", "table of figures"}
CAPTION_PREFIX = re.compile(r"^(Figure|Table)\s+\d+[.:]\s*")


def iter_blocks(doc):
    """Yield Paragraph / Table / 'SECT' in document order."""
    for child in doc.element.body.iterchildren():
        if child.tag == qn("w:p"):
            p = Paragraph(child, doc)
            yield p
            pPr = child.find(qn("w:pPr"))
            if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                yield "SECT"
        elif child.tag == qn("w:tbl"):
            yield Table(child, doc)


def image_of(par, doc):
    """Return (rel_target, width_in, height_in) for the first inline image, else None."""
    blip = par._p.find(".//" + qn("a:blip"))
    if blip is None:
        return None
    rid = blip.get(qn("r:embed"))
    part = doc.part.related_parts[rid]
    ext = par._p.find(".//" + qn("wp:extent"))
    w = int(ext.get("cx")) / EMU_PER_INCH if ext is not None else 6.2
    h = int(ext.get("cy")) / EMU_PER_INCH if ext is not None else 0.0
    return part, round(w, 2), round(h, 2)


def has_page_break(par):
    return any(br.get(qn("w:type")) == "page" for br in par._p.findall(".//" + qn("w:br")))


def cell_text(cell):
    return " ".join(p.text.strip() for p in cell.paragraphs if p.text.strip())


def md_table(tbl):
    rows = [[cell_text(c).replace("|", r"\|") for c in r.cells] for r in tbl.rows]
    if not rows:
        return []
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    out = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * width]
    out += ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return out


def clean(text):
    """Repair the mojibake left by whatever produced the original document."""
    fixes = {
        "\u2019": "'", "\u2018": "'", "\u201c": '"', "\u201d": '"',
        "\u2013": "-", "\u2014": "--", "\ufffd": "'", "\u00a0": " ",
    }
    for bad, good in fixes.items():
        text = text.replace(bad, good)
    return text.strip()


def extract(docx_path: Path, out_dir: Path) -> Path:
    doc = docx.Document(str(docx_path))
    media = out_dir / "media"
    media.mkdir(parents=True, exist_ok=True)
    for old in media.glob("*"):
        old.unlink()

    title_lines: list[str] = []
    body: list[str] = []
    seen_first_sect = False
    pending_caption: str | None = None
    saved: dict[str, str] = {}
    n_img = 0

    def emit(line=""):
        if line == "" and body and body[-1] == "":
            return
        body.append(line)

    for block in iter_blocks(doc):
        if block == "SECT":
            if not seen_first_sect:
                seen_first_sect = True
                emit()
                emit("@@sect roman")
            else:
                emit()
                emit("@@sect arabic")
            emit()
            continue

        if isinstance(block, Table):
            if pending_caption:
                emit(f"Table: {pending_caption}")
                pending_caption = None
            body.extend(md_table(block))
            emit()
            continue

        par = block
        style = par.style.name if par.style is not None else "Normal"
        text = clean(par.text)

        if style in GENERATED_STYLES:
            continue

        if not seen_first_sect:
            title_lines.extend(l.strip() for l in text.splitlines() if l.strip())
            continue

        img = image_of(par, doc)
        if img is not None:
            part, w, h = img
            n_img += 1
            name = f"figure{n_img:02d}{Path(part.partname).suffix}"
            key = str(part.partname)
            if key in saved:
                name = saved[key]
            else:
                (media / name).write_bytes(part.blob)
                saved[key] = name
            emit(f"@@figure {name} {w}x{h}")
            continue

        if style == "Caption":
            caption = CAPTION_PREFIX.sub("", text)
            if body and body[-1].startswith("@@figure "):
                body[-1] += f" :: {caption}"
            else:
                pending_caption = caption
            continue

        if not text:
            if has_page_break(par):
                emit()
                emit("@@pagebreak")
                emit()
            continue

        if style == "Front Matter Heading":
            emit()
            emit(f"@@front {text}")
            emit()
            low = text.lower()
            if low == "table of contents":
                emit("@@toc")
                emit()
        elif style == "Heading 1":
            emit()
            emit(f"# {text}")
            emit()
        elif style == "Heading 2":
            emit()
            emit(f"## {text}")
            emit()
            low = text.lower()
            if low == "list of figures":
                emit("@@lof")
                emit()
            elif low == "list of tables":
                emit("@@lot")
                emit()
        elif style in ("List Bullet", "List Paragraph"):
            emit(f"- {text}")
        else:
            emit(text)
            emit()

    def pick(pattern, default=""):
        for line in title_lines:
            if re.match(pattern, line, re.I):
                return line
        return default

    kicker = title_lines[0] if title_lines else "FINAL PROJECT REPORT"
    title = title_lines[1] if len(title_lines) > 1 else "Report"
    subtitle = title_lines[2] if len(title_lines) > 2 else ""
    author = title_lines[3] if len(title_lines) > 3 else ""
    student = pick(r"student id", "").split(":", 1)[-1].strip()
    supervisor = pick(r"supervisor", "").split(":", 1)[-1].strip()
    tail = [l for l in title_lines[4:] if not re.match(r"student id|supervisor", l, re.I)]

    front = [
        "---",
        f"kicker: {kicker}",
        f"title: {title}",
        f"subtitle: {subtitle}",
        f"author: {author}",
        f"student_id: {student}",
        f"supervisor: {supervisor}",
        f"affiliation: {' | '.join(tail)}",
        "header_front: EasyRTG | Final Project Report",
        f"header_body: EasyRTG | {subtitle}",
        "---",
        "",
    ]

    while body and body[-1] == "":
        body.pop()
    md = out_dir / "report.md"
    md.write_text("\n".join(front + body) + "\n", encoding="utf-8")
    return md


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parents[1]
    ap.add_argument("--docx", type=Path, default=root / "EasyRTG_Project_Report_Shivam_Chavan.docx")
    ap.add_argument("--out", type=Path, default=root / "report")
    a = ap.parse_args()
    md = extract(a.docx, a.out)
    n_media = len(list((a.out / "media").glob("*")))
    print(f"wrote {md} ({len(md.read_text(encoding='utf-8').splitlines())} lines, {n_media} images)")


if __name__ == "__main__":
    main()
